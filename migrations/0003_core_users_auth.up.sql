-- 0003 core / users & authentication — accounts, server-side sessions, tokens
-- The session row is the source of truth for active_gate_id. Never trust a gate
-- sent by the browser; validate it against gate_users on every request.
-- Re-runnable: CREATE TABLE IF NOT EXISTS only.
-- =============================================================================

CREATE TABLE IF NOT EXISTS users (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    first_name              VARCHAR(128)    NOT NULL,
    last_name               VARCHAR(128)    NOT NULL,
    middle_name             VARCHAR(128)    NULL,
    display_name            VARCHAR(255)    NULL,
    email                   VARCHAR(255)    NULL,
    phone                   VARCHAR(32)     NULL,
    username                VARCHAR(64)     NULL,
    password_hash           VARCHAR(255)    NULL,
    avatar_path             VARCHAR(512)    NULL,
    job_title               VARCHAR(128)    NULL,
    preferred_timezone      VARCHAR(64)     NULL,
    preferred_locale        VARCHAR(10)     NULL,
    status                  VARCHAR(16)     NOT NULL DEFAULT 'invited',
    is_super_admin          TINYINT(1)      NOT NULL DEFAULT 0 COMMENT 'platform operator, crosses tenants',
    must_change_password    TINYINT(1)      NOT NULL DEFAULT 0,
    mfa_enabled             TINYINT(1)      NOT NULL DEFAULT 0,
    mfa_method              VARCHAR(16)     NULL,
    mfa_secret_ciphertext   TEXT            NULL COMMENT 'sealed with the tenant encryption key',
    failed_attempts         SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    locked_until            DATETIME(6)     NULL,
    email_verified_at       DATETIME(6)     NULL,
    phone_verified_at       DATETIME(6)     NULL,
    last_login_at           DATETIME(6)     NULL,
    last_active_at          DATETIME(6)     NULL,
    external_ref            VARCHAR(128)    NULL COMMENT 'HR / ERP identifier for staff sync',
    notes                   TEXT            NULL,
    created_by              BIGINT UNSIGNED NULL,
    updated_by              BIGINT UNSIGNED NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at              DATETIME(6)     NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_users_email (tenant_id, email),
    UNIQUE KEY uk_users_username (tenant_id, username),
    UNIQUE KEY uk_users_external_ref (tenant_id, external_ref),
    UNIQUE KEY uk_users_id_tenant (id, tenant_id),
    KEY idx_users_name (tenant_id, last_name, first_name),
    KEY idx_users_phone (tenant_id, phone),
    KEY idx_users_status (tenant_id, status, deleted_at),
    KEY idx_users_last_active (tenant_id, last_active_at),
    CONSTRAINT fk_users_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_users_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_users_updater FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_users_status CHECK (status IN ('invited', 'active', 'disabled', 'locked', 'archived')),
    CONSTRAINT chk_users_mfa_method CHECK (mfa_method IS NULL OR mfa_method IN ('totp', 'sms', 'email', 'push')),
    CONSTRAINT chk_users_flags CHECK (is_super_admin IN (0, 1) AND must_change_password IN (0, 1) AND mfa_enabled IN (0, 1)),
    CONSTRAINT chk_users_name_required CHECK (CHAR_LENGTH(TRIM(first_name)) > 0 AND CHAR_LENGTH(TRIM(last_name)) > 0)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS user_sessions (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    user_id                 BIGINT UNSIGNED NOT NULL,
    session_hash            CHAR(64)        NOT NULL COMMENT 'SHA-256 of the cookie token',
    active_site_id          BIGINT UNSIGNED NULL,
    active_gate_id          BIGINT UNSIGNED NULL,
    device_id               BIGINT UNSIGNED NULL COMMENT 'set when the gate came from a registered device',
    auth_method             VARCHAR(24)     NOT NULL DEFAULT 'password',
    ip_address              VARCHAR(45)     NULL,
    user_agent              VARCHAR(255)    NULL,
    is_remembered           TINYINT(1)      NOT NULL DEFAULT 0,
    rotates_at              DATETIME(6)     NULL COMMENT 'idle timeout deadline',
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    last_seen_at            DATETIME(6)     NULL,
    expires_at              DATETIME(6)     NOT NULL,
    revoked_at              DATETIME(6)     NULL,
    revoke_reason           VARCHAR(64)     NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_user_sessions_hash (session_hash),
    KEY idx_user_sessions_user (user_id, revoked_at, expires_at),
    KEY idx_user_sessions_tenant (tenant_id, expires_at),
    KEY idx_user_sessions_gate (active_gate_id),
    CONSTRAINT fk_user_sessions_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_sessions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_sessions_site FOREIGN KEY (active_site_id) REFERENCES sites (id) ON DELETE SET NULL,
    CONSTRAINT fk_user_sessions_gate FOREIGN KEY (active_gate_id) REFERENCES gates (id) ON DELETE SET NULL,
    CONSTRAINT fk_user_sessions_device FOREIGN KEY (device_id) REFERENCES gate_devices (id) ON DELETE SET NULL,
    CONSTRAINT chk_user_sessions_auth CHECK (auth_method IN ('password', 'device_pin', 'sso', 'api_key', 'impersonation')),
    CONSTRAINT chk_user_sessions_remember CHECK (is_remembered IN (0, 1))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS user_tokens (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    user_id                 BIGINT UNSIGNED NULL,
    token_hash              CHAR(64)        NOT NULL,
    purpose                 VARCHAR(24)     NOT NULL,
    target_value            VARCHAR(255)    NULL COMMENT 'email or phone the token applies to',
    requested_by            BIGINT UNSIGNED NULL,
    ip_address              VARCHAR(45)     NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    expires_at              DATETIME(6)     NOT NULL,
    used_at                 DATETIME(6)     NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_user_tokens_hash (token_hash),
    KEY idx_user_tokens_user (tenant_id, user_id, purpose, used_at),
    CONSTRAINT fk_user_tokens_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT chk_user_tokens_purpose CHECK (purpose IN ('password_reset', 'invite', 'email_change', 'phone_change', 'mfa_recovery'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS login_attempts (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '0 when the tenant could not be resolved',
    user_id                 BIGINT UNSIGNED NULL,
    identifier              VARCHAR(255)    NULL COMMENT 'what was typed, email, username or phone',
    outcome                 VARCHAR(16)     NOT NULL,
    failure_reason          VARCHAR(48)     NULL,
    ip_address              VARCHAR(45)     NULL,
    user_agent              VARCHAR(255)    NULL,
    occurred_at             DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    KEY idx_login_attempts_tenant (tenant_id, occurred_at),
    KEY idx_login_attempts_identifier (tenant_id, identifier, occurred_at),
    KEY idx_login_attempts_ip (ip_address, occurred_at),
    CONSTRAINT fk_login_attempts_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_login_attempts_outcome CHECK (outcome IN ('success', 'failure', 'blocked', 'mfa_failure', 'logout'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;
