-- =============================================================================
-- 0007 core / passes — one header row per pass, every module owns a detail row
-- passes is the spine: gate_movements, approvals, tokens, rules and reports all
-- point at it. Module detail tables hang off pass_id with a 1:1 link.
-- Status is VARCHAR plus CHECK, never ENUM, so a new state is a migration and
-- not a schema rewrite.
-- Re-runnable: CREATE TABLE IF NOT EXISTS only.
-- =============================================================================

CREATE TABLE IF NOT EXISTS pass_types (
    id                      SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT,
    type_key                VARCHAR(64)     NOT NULL,
    name                    VARCHAR(128)    NOT NULL,
    module_key              VARCHAR(64)     NOT NULL,
    category_key            VARCHAR(64)     NOT NULL COMMENT 'matched against gate_categories',
    requires_approval       TINYINT(1)      NOT NULL DEFAULT 1,
    requires_host           TINYINT(1)      NOT NULL DEFAULT 0,
    requires_vehicle        TINYINT(1)      NOT NULL DEFAULT 0,
    requires_items          TINYINT(1)      NOT NULL DEFAULT 0,
    requires_document_check TINYINT(1)      NOT NULL DEFAULT 0,
    default_validity_hours  SMALLINT UNSIGNED NULL,
    default_max_entries     SMALLINT UNSIGNED NULL COMMENT 'NULL = unlimited within the validity window',
    default_dwell_limit_minutes INT UNSIGNED NULL,
    description             VARCHAR(255)    NULL,
    status                  VARCHAR(16)     NOT NULL DEFAULT 'active',
    sort_order              SMALLINT        NOT NULL DEFAULT 100,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_pass_types_key (type_key),
    KEY idx_pass_types_module (module_key, status),
    CONSTRAINT fk_pass_types_module FOREIGN KEY (module_key) REFERENCES modules (module_key) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_pass_types_category FOREIGN KEY (category_key) REFERENCES pass_categories (category_key) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_pass_types_flags CHECK (requires_approval IN (0, 1) AND requires_host IN (0, 1) AND requires_vehicle IN (0, 1) AND requires_items IN (0, 1) AND requires_document_check IN (0, 1)),
    CONSTRAINT chk_pass_types_status CHECK (status IN ('active', 'inactive'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS passes (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    uuid                    CHAR(36)        NOT NULL,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    site_id                 BIGINT UNSIGNED NOT NULL,
    pass_type_id            SMALLINT UNSIGNED NOT NULL,
    category_key            VARCHAR(64)     NOT NULL COMMENT 'snapshot of the type category at issue time',
    source_module_key       VARCHAR(64)     NOT NULL,
    pass_no                 VARCHAR(32)     NOT NULL COMMENT 'human readable reference printed on the badge',
    reference_no            VARCHAR(64)     NULL COMMENT 'waybill, invoice or ticket from the source system',
    status                  VARCHAR(24)     NOT NULL DEFAULT 'draft',
    origin                  VARCHAR(24)     NOT NULL DEFAULT 'walk_in',
    subject_name            VARCHAR(255)    NULL COMMENT 'person or thing the pass covers when there is no account',
    subject_phone           VARCHAR(32)     NULL,
    subject_email           VARCHAR(255)    NULL,
    subject_document_no     VARCHAR(64)     NULL COMMENT 'ID or permit number, retention purged',
    subject_document_purged_at DATETIME(6)  NULL,
    requester_user_id       BIGINT UNSIGNED NULL,
    host_user_id            BIGINT UNSIGNED NULL,
    department_id           BIGINT UNSIGNED NULL,
    parent_pass_id          BIGINT UNSIGNED NULL COMMENT 're-issue, renewal or a child item pass',
    title                   VARCHAR(255)    NULL,
    purpose                 VARCHAR(512)    NULL,
    reason_code             VARCHAR(32)     NULL,
    value_amount            DECIMAL(14, 2)  NULL COMMENT 'declared value, feeds rule thresholds',
    value_currency          CHAR(3)         NULL,
    valid_from              DATETIME(6)     NOT NULL,
    valid_until             DATETIME(6)     NULL,
    max_entries             SMALLINT UNSIGNED NULL,
    entry_count             SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    exit_count              SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    issued_at               DATETIME(6)     NULL,
    decided_by_user_id      BIGINT UNSIGNED NULL,
    decided_at              DATETIME(6)     NULL,
    decision_note           VARCHAR(512)    NULL,
    closed_at               DATETIME(6)     NULL,
    created_by              BIGINT UNSIGNED NULL,
    updated_by              BIGINT UNSIGNED NULL,
    metadata                JSON            NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at              DATETIME(6)     NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_passes_uuid (uuid),
    UNIQUE KEY uk_passes_no (tenant_id, pass_no),
    UNIQUE KEY uk_passes_id_tenant (id, tenant_id),
    KEY idx_passes_lookup (tenant_id, source_module_key, status, valid_from),
    KEY idx_passes_type (tenant_id, pass_type_id, status),
    KEY idx_passes_host (tenant_id, host_user_id, status),
    KEY idx_passes_requester (tenant_id, requester_user_id, status),
    KEY idx_passes_valid_until (tenant_id, status, valid_until),
    KEY idx_passes_subject_phone (tenant_id, subject_phone),
    KEY idx_passes_site (tenant_id, site_id, status),
    FULLTEXT KEY ft_passes_subject (subject_name, title, purpose),
    CONSTRAINT fk_passes_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_passes_site FOREIGN KEY (site_id, tenant_id) REFERENCES sites (id, tenant_id) ON DELETE RESTRICT,
    CONSTRAINT fk_passes_type FOREIGN KEY (pass_type_id) REFERENCES pass_types (id) ON DELETE RESTRICT,
    CONSTRAINT fk_passes_category FOREIGN KEY (category_key) REFERENCES pass_categories (category_key) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_passes_module FOREIGN KEY (source_module_key) REFERENCES modules (module_key) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_passes_requester FOREIGN KEY (requester_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_passes_host FOREIGN KEY (host_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_passes_department FOREIGN KEY (department_id) REFERENCES departments (id) ON DELETE SET NULL,
    CONSTRAINT fk_passes_parent FOREIGN KEY (parent_pass_id) REFERENCES passes (id) ON DELETE SET NULL,
    CONSTRAINT fk_passes_decider FOREIGN KEY (decided_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_passes_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_passes_updater FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_passes_status CHECK (status IN ('draft', 'pending', 'pending_review', 'approved', 'rejected', 'cancelled', 'expired', 'active', 'on_site', 'completed', 'returned', 'overdue', 'void')),
    CONSTRAINT chk_passes_origin CHECK (origin IN ('walk_in', 'pre_registered', 'online', 'api', 'import', 'device', 'renewal')),
    CONSTRAINT chk_passes_window CHECK (valid_until IS NULL OR valid_until >= valid_from)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS pass_gates (
    pass_id                 BIGINT UNSIGNED NOT NULL,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    gate_id                 BIGINT UNSIGNED NOT NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (pass_id, gate_id),
    KEY idx_pass_gates_gate (gate_id, pass_id),
    KEY idx_pass_gates_tenant (tenant_id, pass_id),
    CONSTRAINT fk_pass_gates_pass FOREIGN KEY (pass_id, tenant_id) REFERENCES passes (id, tenant_id) ON DELETE CASCADE,
    CONSTRAINT fk_pass_gates_gate FOREIGN KEY (gate_id) REFERENCES gates (id) ON DELETE CASCADE
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS pass_attachments (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    pass_id                 BIGINT UNSIGNED NOT NULL,
    kind                    VARCHAR(24)     NOT NULL,
    file_path               VARCHAR(512)    NOT NULL,
    original_name           VARCHAR(255)    NULL,
    mime_type               VARCHAR(64)     NULL,
    size_bytes              BIGINT UNSIGNED NULL,
    sha256                  CHAR(64)        NULL,
    capture_device_id       BIGINT UNSIGNED NULL,
    expires_at              DATETIME(6)     NULL COMMENT 'retention deadline, compliance module purges on it',
    purged_at               DATETIME(6)     NULL,
    uploaded_by             BIGINT UNSIGNED NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    KEY idx_pass_attachments_pass (pass_id, kind, purged_at),
    KEY idx_pass_attachments_retention (tenant_id, expires_at, purged_at),
    CONSTRAINT fk_pass_attachments_pass FOREIGN KEY (pass_id, tenant_id) REFERENCES passes (id, tenant_id) ON DELETE CASCADE,
    CONSTRAINT fk_pass_attachments_device FOREIGN KEY (capture_device_id) REFERENCES gate_devices (id) ON DELETE SET NULL,
    CONSTRAINT fk_pass_attachments_uploader FOREIGN KEY (uploaded_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_pass_attachments_kind CHECK (kind IN ('id_document', 'face', 'vehicle', 'goods', 'permit', 'signature', 'other'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS pass_status_history (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    pass_id                 BIGINT UNSIGNED NOT NULL,
    from_status             VARCHAR(24)     NULL,
    to_status               VARCHAR(24)     NOT NULL,
    changed_by_user_id      BIGINT UNSIGNED NULL,
    gate_session_id         BIGINT UNSIGNED NULL,
    reason_code             VARCHAR(32)     NULL,
    reason_note             VARCHAR(512)    NULL,
    source                  VARCHAR(16)     NOT NULL DEFAULT 'manual',
    occurred_at             DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    KEY idx_pass_status_history_pass (pass_id, occurred_at),
    KEY idx_pass_status_history_tenant (tenant_id, occurred_at),
    CONSTRAINT fk_pass_status_history_pass FOREIGN KEY (pass_id, tenant_id) REFERENCES passes (id, tenant_id) ON DELETE CASCADE,
    CONSTRAINT fk_pass_status_history_user FOREIGN KEY (changed_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_pass_status_history_session FOREIGN KEY (gate_session_id) REFERENCES gate_sessions (id) ON DELETE SET NULL,
    CONSTRAINT chk_pass_status_history_source CHECK (source IN ('manual', 'scan', 'approval', 'scheduler', 'sync', 'api', 'rule', 'system'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;
