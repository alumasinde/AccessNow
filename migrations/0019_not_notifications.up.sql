-- =============================================================================
-- 0019 module / notifications — templates, routing and the delivery queue
-- An event key such as pass.awaiting_approval maps to routes (who hears) and a
-- template per channel and locale. Queued rows carry available_at so retries and
-- delays need no external scheduler.
-- Standalone default: in-app notices only, which is the same table with
-- channel = in_app.
-- Re-runnable: CREATE TABLE IF NOT EXISTS only.
-- =============================================================================

CREATE TABLE IF NOT EXISTS notification_events (
    id                      SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT,
    event_key               VARCHAR(64)     NOT NULL COMMENT 'mirrors domain_events.event_key',
    name                    VARCHAR(128)    NOT NULL,
    module_key              VARCHAR(64)     NOT NULL,
    default_channels        JSON            NULL COMMENT 'the channels a fresh tenant gets',
    default_recipient_types JSON            NULL COMMENT 'host, gate_supervisor, tenant_admin',
    is_opt_out              TINYINT(1)      NOT NULL DEFAULT 0 COMMENT 'false means the tenant must ask to receive it',
    status                  VARCHAR(16)     NOT NULL DEFAULT 'active',
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_notification_events_key (event_key),
    KEY idx_notification_events_module (module_key, status),
    CONSTRAINT fk_notification_events_module FOREIGN KEY (module_key) REFERENCES modules (module_key) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_notification_events_opt_out CHECK (is_opt_out IN (0, 1)),
    CONSTRAINT chk_notification_events_status CHECK (status IN ('active', 'inactive'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS notification_templates (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NULL COMMENT 'NULL = the system default every tenant inherits',
    event_key               VARCHAR(64)     NOT NULL,
    channel                 VARCHAR(16)     NOT NULL,
    locale                  VARCHAR(10)     NOT NULL DEFAULT 'en',
    subject                 VARCHAR(255)    NULL,
    body                    TEXT            NOT NULL,
    short_body              VARCHAR(320)    NULL COMMENT 'SMS and WhatsApp length',
    is_html                 TINYINT(1)      NOT NULL DEFAULT 0,
    variables               JSON            NULL COMMENT 'the placeholders the renderer must fill',
    version                 INT UNSIGNED    NOT NULL DEFAULT 1,
    status                  VARCHAR(16)     NOT NULL DEFAULT 'active',
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    tenant_scope_key        BIGINT UNSIGNED GENERATED ALWAYS AS (IFNULL(tenant_id, 0)) STORED COMMENT '0 lets the unique key cover system defaults too',
    PRIMARY KEY (id),
    UNIQUE KEY uk_notification_templates (tenant_scope_key, event_key, channel, locale),
    KEY idx_notification_templates_event (event_key, channel, status),
    CONSTRAINT fk_notification_templates_event FOREIGN KEY (event_key) REFERENCES notification_events (event_key) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_notification_templates_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT chk_notification_templates_channel CHECK (channel IN ('in_app', 'email', 'sms', 'whatsapp', 'push', 'webhook')),
    CONSTRAINT chk_notification_templates_html CHECK (is_html IN (0, 1)),
    CONSTRAINT chk_notification_templates_status CHECK (status IN ('active', 'inactive'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS notification_routes (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    event_key               VARCHAR(64)     NOT NULL,
    channel                 VARCHAR(16)     NOT NULL,
    recipient_type          VARCHAR(24)     NOT NULL,
    recipient_user_id       BIGINT UNSIGNED NULL,
    recipient_role_key      VARCHAR(64)     NULL,
    recipient_address       VARCHAR(255)    NULL COMMENT 'static address for recipient_type = static',
    site_id                 BIGINT UNSIGNED NULL,
    gate_id                 BIGINT UNSIGNED NULL,
    include_actor           TINYINT(1)      NOT NULL DEFAULT 0 COMMENT 'also notify whoever caused the event',
    is_active               TINYINT(1)      NOT NULL DEFAULT 1,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_notification_routes (tenant_id, event_key, channel, recipient_type, recipient_user_id, recipient_role_key, recipient_address),
    KEY idx_notification_routes_event (tenant_id, event_key, is_active),
    KEY idx_notification_routes_user (recipient_user_id, is_active),
    CONSTRAINT fk_notification_routes_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_notification_routes_event FOREIGN KEY (event_key) REFERENCES notification_events (event_key) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_notification_routes_user FOREIGN KEY (recipient_user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_notification_routes_site FOREIGN KEY (site_id) REFERENCES sites (id) ON DELETE CASCADE,
    CONSTRAINT fk_notification_routes_gate FOREIGN KEY (gate_id) REFERENCES gates (id) ON DELETE CASCADE,
    CONSTRAINT chk_notification_routes_channel CHECK (channel IN ('in_app', 'email', 'sms', 'whatsapp', 'push', 'webhook')),
    CONSTRAINT chk_notification_routes_recipient CHECK (recipient_type IN ('user', 'role', 'host', 'requester', 'approver', 'gate_supervisor', 'site_supervisor', 'department_head', 'tenant_admin', 'static')),
    CONSTRAINT chk_notification_routes_target CHECK (recipient_type NOT IN ('user', 'static') OR recipient_user_id IS NOT NULL OR recipient_address IS NOT NULL),
    CONSTRAINT chk_notification_routes_role CHECK (recipient_type <> 'role' OR recipient_role_key IS NOT NULL),
    CONSTRAINT chk_notification_routes_flags CHECK (include_actor IN (0, 1) AND is_active IN (0, 1))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS notifications (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    event_key               VARCHAR(64)     NOT NULL,
    notification_template_id BIGINT UNSIGNED NULL,
    channel                 VARCHAR(16)     NOT NULL,
    locale                  VARCHAR(10)     NOT NULL DEFAULT 'en',
    to_user_id              BIGINT UNSIGNED NULL,
    to_address              VARCHAR(255)    NULL COMMENT 'email, MSISDN or device token, retention purged',
    to_address_purged_at    DATETIME(6)     NULL,
    subject                 VARCHAR(255)    NULL,
    body                    TEXT            NULL COMMENT 'purged after the message body retention window',
    body_purged_at          DATETIME(6)     NULL,
    pass_id                 BIGINT UNSIGNED NULL,
    movement_id             BIGINT UNSIGNED NULL,
    related_type            VARCHAR(48)     NULL,
    related_id              BIGINT UNSIGNED NULL,
    dedupe_key              CHAR(64)        NULL COMMENT 'event plus recipient plus channel, stops a double alert',
    status                  VARCHAR(16)     NOT NULL DEFAULT 'queued',
    attempts                SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    max_attempts            SMALLINT UNSIGNED NOT NULL DEFAULT 5,
    available_at            DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT 'retry backoff lands here',
    queued_at               DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    sent_at                 DATETIME(6)     NULL,
    delivered_at            DATETIME(6)     NULL,
    read_at                 DATETIME(6)     NULL,
    provider                VARCHAR(32)     NULL,
    provider_message_id     VARCHAR(128)    NULL,
    error_code              VARCHAR(48)     NULL,
    error_message           VARCHAR(512)    NULL,
    purge_at                DATETIME(6)     NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_notifications_dedupe (tenant_id, dedupe_key),
    KEY idx_notifications_queue (status, available_at),
    KEY idx_notifications_inbox (tenant_id, to_user_id, channel, read_at),
    KEY idx_notifications_pass (pass_id),
    KEY idx_notifications_purge (tenant_id, purge_at),
    KEY idx_notifications_event (tenant_id, event_key, queued_at),
    CONSTRAINT fk_notifications_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_notifications_template FOREIGN KEY (notification_template_id) REFERENCES notification_templates (id) ON DELETE SET NULL,
    CONSTRAINT fk_notifications_user FOREIGN KEY (to_user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_notifications_pass FOREIGN KEY (pass_id) REFERENCES passes (id) ON DELETE SET NULL,
    CONSTRAINT fk_notifications_movement FOREIGN KEY (movement_id) REFERENCES gate_movements (id) ON DELETE SET NULL,
    CONSTRAINT chk_notifications_channel CHECK (channel IN ('in_app', 'email', 'sms', 'whatsapp', 'push', 'webhook')),
    CONSTRAINT chk_notifications_status CHECK (status IN ('queued', 'sending', 'sent', 'delivered', 'failed', 'bounced', 'cancelled', 'expired'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS notification_providers (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    channel                 VARCHAR(16)     NOT NULL,
    provider                VARCHAR(32)     NOT NULL,
    is_primary              TINYINT(1)      NOT NULL DEFAULT 0,
    sender_id               VARCHAR(128)    NULL COMMENT 'publisher id, short code or from address, not a secret',
    credentials_ref         VARCHAR(255)    NULL COMMENT 'name of the secret in the vault or env, never the secret itself',
    options                 JSON            NULL,
    is_active               TINYINT(1)      NOT NULL DEFAULT 1,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_notification_providers (tenant_id, channel, provider),
    KEY idx_notification_providers_primary (tenant_id, channel, is_primary),
    CONSTRAINT fk_notification_providers_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT chk_notification_providers_channel CHECK (channel IN ('email', 'sms', 'whatsapp', 'push')),
    CONSTRAINT chk_notification_providers_flags CHECK (is_primary IN (0, 1) AND is_active IN (0, 1))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;
