-- =============================================================================
-- 0014 module / contractor & recurring access — long passes with document expiry
-- A pass carries a validity range, allowed gates (pass_gates in core), weekly
-- time windows and multi-entry allowance. An expired mandatory document blocks
-- the pass, which the nightly check enforces by moving the pass to blocked.
-- Re-runnable: CREATE TABLE IF NOT EXISTS only.
-- =============================================================================

CREATE TABLE IF NOT EXISTS contractor_organizations (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    name                    VARCHAR(255)    NOT NULL,
    short_name              VARCHAR(64)     NULL,
    registration_no         VARCHAR(64)     NULL,
    tax_id                  VARCHAR(64)     NULL,
    trade                   VARCHAR(128)    NULL COMMENT 'works, supply, cleaning, security, transport',
    contact_name            VARCHAR(128)    NULL,
    contact_email           VARCHAR(255)    NULL,
    contact_phone           VARCHAR(32)     NULL,
    address                 VARCHAR(255)    NULL,
    contract_ref            VARCHAR(64)     NULL,
    contract_start          DATE            NULL,
    contract_end            DATE            NULL,
    status                  VARCHAR(16)     NOT NULL DEFAULT 'active',
    notes                   TEXT            NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at              DATETIME(6)     NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_contractor_org_name (tenant_id, name),
    UNIQUE KEY uk_contractor_org_reg (tenant_id, registration_no),
    UNIQUE KEY uk_contractor_org_id_tenant (id, tenant_id),
    KEY idx_contractor_org_contract_end (tenant_id, contract_end, status),
    CONSTRAINT fk_contractor_org_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT chk_contractor_org_status CHECK (status IN ('active', 'pending', 'suspended', 'archived'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS contractors (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    organization_id         BIGINT UNSIGNED NULL,
    first_name              VARCHAR(128)    NOT NULL,
    last_name               VARCHAR(128)    NOT NULL,
    phone                   VARCHAR(32)     NULL,
    email                   VARCHAR(255)    NULL,
    nationality             CHAR(2)         NULL,
    id_type                 VARCHAR(24)     NULL,
    id_number               VARCHAR(64)     NULL,
    id_number_purged_at     DATETIME(6)     NULL,
    photo_path              VARCHAR(512)    NULL,
    photo_purged_at         DATETIME(6)     NULL,
    badge_no                VARCHAR(64)     NULL,
    access_card_no          VARCHAR(64)     NULL,
    trade                   VARCHAR(128)    NULL,
    sponsor_user_id         BIGINT UNSIGNED NULL COMMENT 'the tenant employee who vouched for them',
    sponsor_department_id   BIGINT UNSIGNED NULL,
    status                  VARCHAR(16)     NOT NULL DEFAULT 'pending',
    documents_verified_at   DATETIME(6)     NULL,
    notes                   TEXT            NULL,
    external_ref            VARCHAR(128)    NULL,
    created_by              BIGINT UNSIGNED NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at              DATETIME(6)     NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_contractors_id_number (tenant_id, id_number),
    UNIQUE KEY uk_contractors_external_ref (tenant_id, external_ref),
    UNIQUE KEY uk_contractors_id_tenant (id, tenant_id),
    KEY idx_contractors_name (tenant_id, last_name, first_name, deleted_at),
    KEY idx_contractors_org (organization_id),
    KEY idx_contractors_phone (tenant_id, phone),
    KEY idx_contractors_status (tenant_id, status),
    FULLTEXT KEY ft_contractors_name (first_name, last_name),
    CONSTRAINT fk_contractors_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_contractors_org FOREIGN KEY (organization_id) REFERENCES contractor_organizations (id) ON DELETE SET NULL,
    CONSTRAINT fk_contractors_sponsor FOREIGN KEY (sponsor_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_contractors_department FOREIGN KEY (sponsor_department_id) REFERENCES departments (id) ON DELETE SET NULL,
    CONSTRAINT fk_contractors_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_contractors_status CHECK (status IN ('pending', 'active', 'suspended', 'expired', 'archived')),
    CONSTRAINT chk_contractors_id_type CHECK (id_type IS NULL OR id_type IN ('national_id', 'passport', 'drivers_licence', 'work_permit', 'other')),
    CONSTRAINT chk_contractors_name_required CHECK (CHAR_LENGTH(TRIM(first_name)) > 0 AND CHAR_LENGTH(TRIM(last_name)) > 0)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS document_types (
    id                      SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT,
    type_key                VARCHAR(64)     NOT NULL COMMENT 'work_permit, insurance, induction, vehicle_permit, hazmat',
    name                    VARCHAR(128)    NOT NULL,
    holder_type             VARCHAR(16)     NOT NULL DEFAULT 'contractor' COMMENT 'contractor, vehicle, organization',
    applies_to_module       VARCHAR(64)     NULL,
    is_mandatory            TINYINT(1)      NOT NULL DEFAULT 1,
    validity_months         SMALLINT UNSIGNED NULL,
    requires_verification   TINYINT(1)      NOT NULL DEFAULT 1,
    reminder_days_before    SMALLINT UNSIGNED NOT NULL DEFAULT 30,
    status                  VARCHAR(16)     NOT NULL DEFAULT 'active',
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_document_types_key (type_key),
    CONSTRAINT chk_document_types_holder CHECK (holder_type IN ('contractor', 'vehicle', 'organization', 'visitor', 'staff')),
    CONSTRAINT chk_document_types_flags CHECK (is_mandatory IN (0, 1) AND requires_verification IN (0, 1)),
    CONSTRAINT chk_document_types_status CHECK (status IN ('active', 'inactive'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS contractor_documents (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    contractor_id           BIGINT UNSIGNED NOT NULL,
    document_type_key       VARCHAR(64)     NOT NULL,
    document_no             VARCHAR(128)    NULL,
    issuing_authority       VARCHAR(255)    NULL,
    issued_at               DATE            NULL,
    valid_from              DATE            NULL,
    expires_on              DATE            NULL COMMENT 'an expired mandatory document blocks every pass of this contractor',
    attachment_path         VARCHAR(512)    NULL,
    attachment_purged_at    DATETIME(6)     NULL,
    status                  VARCHAR(16)     NOT NULL DEFAULT 'pending',
    verified_by_user_id     BIGINT UNSIGNED NULL,
    verified_at             DATETIME(6)     NULL,
    rejection_reason        VARCHAR(512)    NULL,
    reminder_sent_at        DATETIME(6)     NULL,
    notes                   VARCHAR(512)    NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_contractor_documents (tenant_id, contractor_id, document_type_key, document_no),
    KEY idx_contractor_documents_expiry (tenant_id, status, expires_on),
    KEY idx_contractor_documents_contractor (contractor_id),
    CONSTRAINT fk_contractor_documents_contractor FOREIGN KEY (contractor_id, tenant_id) REFERENCES contractors (id, tenant_id) ON DELETE CASCADE,
    CONSTRAINT fk_contractor_documents_type FOREIGN KEY (document_type_key) REFERENCES document_types (type_key) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_contractor_documents_verifier FOREIGN KEY (verified_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_contractor_documents_status CHECK (status IN ('pending', 'valid', 'expiring', 'expired', 'rejected', 'withdrawn')),
    CONSTRAINT chk_contractor_documents_window CHECK (expires_on IS NULL OR valid_from IS NULL OR expires_on >= valid_from)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS contractor_passes (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    pass_id                 BIGINT UNSIGNED NOT NULL,
    contractor_id           BIGINT UNSIGNED NOT NULL,
    organization_id         BIGINT UNSIGNED NULL,
    site_id                 BIGINT UNSIGNED NOT NULL,
    badge_no                VARCHAR(64)     NULL,
    is_multi_entry          TINYINT(1)      NOT NULL DEFAULT 1,
    valid_from              DATE            NOT NULL,
    valid_to                DATE            NOT NULL,
    work_order_ref          VARCHAR(64)     NULL,
    induction_completed_at  DATETIME(6)     NULL,
    induction_due_on        DATE            NULL,
    escort_required         TINYINT(1)      NOT NULL DEFAULT 0,
    access_zone             VARCHAR(128)    NULL,
    blocked_reason          VARCHAR(255)    NULL COMMENT 'why an automatic document check stopped this pass',
    blocked_at              DATETIME(6)     NULL,
    status                  VARCHAR(24)     NOT NULL DEFAULT 'pending',
    notes                   TEXT            NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_contractor_passes_pass (pass_id),
    UNIQUE KEY uk_contractor_passes_id_tenant (id, tenant_id),
    KEY idx_contractor_passes_contractor (tenant_id, contractor_id, status),
    KEY idx_contractor_passes_validity (tenant_id, status, valid_to),
    KEY idx_contractor_passes_org (organization_id),
    CONSTRAINT fk_contractor_passes_pass FOREIGN KEY (pass_id, tenant_id) REFERENCES passes (id, tenant_id) ON DELETE CASCADE,
    CONSTRAINT fk_contractor_passes_contractor FOREIGN KEY (contractor_id, tenant_id) REFERENCES contractors (id, tenant_id) ON DELETE RESTRICT,
    CONSTRAINT fk_contractor_passes_org FOREIGN KEY (organization_id) REFERENCES contractor_organizations (id) ON DELETE SET NULL,
    CONSTRAINT fk_contractor_passes_site FOREIGN KEY (site_id, tenant_id) REFERENCES sites (id, tenant_id) ON DELETE RESTRICT,
    CONSTRAINT chk_contractor_passes_window CHECK (valid_to >= valid_from),
    CONSTRAINT chk_contractor_passes_flags CHECK (is_multi_entry IN (0, 1) AND escort_required IN (0, 1)),
    CONSTRAINT chk_contractor_passes_status CHECK (status IN ('pending', 'active', 'expired', 'blocked', 'revoked'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS contractor_pass_windows (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    contractor_pass_id      BIGINT UNSIGNED NOT NULL,
    gate_id                 BIGINT UNSIGNED NULL COMMENT 'NULL = any allowed gate of the pass',
    day_of_week             TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'ISO 1 Monday .. 7 Sunday, 0 = every day',
    starts_at               TIME            NOT NULL,
    closes_at               TIME            NOT NULL,
    crosses_midnight        TINYINT(1)      NOT NULL DEFAULT 0,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_contractor_pass_windows (contractor_pass_id, day_of_week, starts_at, closes_at),
    KEY idx_contractor_pass_windows_gate (gate_id),
    CONSTRAINT fk_contractor_pass_windows_pass FOREIGN KEY (contractor_pass_id, tenant_id) REFERENCES contractor_passes (id, tenant_id) ON DELETE CASCADE,
    CONSTRAINT fk_contractor_pass_windows_gate FOREIGN KEY (gate_id) REFERENCES gates (id) ON DELETE CASCADE,
    CONSTRAINT chk_contractor_pass_windows_day CHECK (day_of_week BETWEEN 0 AND 7),
    CONSTRAINT chk_contractor_pass_windows_cross CHECK (crosses_midnight IN (0, 1))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;
