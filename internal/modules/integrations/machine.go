// The permission keys a machine credential is checked against. They are the same keys the desk
// uses, because a scope is a permission: a key that was never granted visitor.view cannot read
// visitors, even if it can read passes.
const (
	ScopeVisitorRead = "visitor.view"
	ScopePassRead    = "core.pass.view"
	ScopeGateRead    = "core.gate.view"
)

// passNumberPattern is what a path segment must look like before it reaches a query. A pass
// number is generated by Core, so refusing anything else keeps a path from carrying SQL or a
// wildcard into the lookup.
var passNumberPattern = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$`)

// machine authorises one request and returns the tenant scope. A missing scope is a 403, not a
// 404: the credential is valid, it simply was not granted this surface.
func (h *Handler) machine(w http.ResponseWriter, r *http.Request, scope string) (tenancy.Scope, bool) {
	key, ok := keyFrom(r.Context())
	if !ok {
		httpx.Fail(r.Context(), w, r, errs.Unauthenticated("api key is required"))
		return tenancy.Scope{}, false
	}
	if !key.Allows(scope) {
		httpx.Fail(r.Context(), w, r, errs.Forbidden("api key is missing the "+scope+" scope"))
		return tenancy.Scope{}, false
	}
	tenant, err := tenancy.Require(r.Context())
	if err != nil {
		httpx.Fail(r.Context(), w, r, err)
		return tenancy.Scope{}, false
	}
	return tenant, true
}

// MachineVisitors is the read a pre-registration or a kiosk integration needs: who is on file,
// not who is on site. On-site is a movement question and stays behind the gate surface.
func (h *Handler) MachineVisitors(w http.ResponseWriter, r *http.Request) {
	scope, ok := h.machine(w, r, ScopeVisitorRead)
	if !ok {
		return
	}
	items, err := h.svc.MachineVisitors(r.Context(), scope.TenantID, 100)
	if err != nil {
		httpx.Fail(r.Context(), w, r, err)
		return
	}
	httpx.OK(w, map[string]any{"items": items})
}

// MachinePass looks one pass up by the number a scanner or a barrier would hold.
func (h *Handler) MachinePass(w http.ResponseWriter, r *http.Request) {
	scope, ok := h.machine(w, r, ScopePassRead)
	if !ok {
		return
	}
	number := chi.URLParam(r, "passNo")
	if !passNumberPattern.MatchString(number) {
		httpx.Fail(r.Context(), w, r, errs.BadField("pass_no", "is not a pass number"))
		return
	}
	pass, err := h.svc.MachinePass(r.Context(), scope.TenantID, number)
	if err != nil {
		httpx.Fail(r.Context(), w, r, err)
		return
	}
	httpx.OK(w, pass)
}

// MachineMovements is the recent register a video or access-control system reconciles against.
// The window is capped: a machine that asks for a year is asking for the table.
func (h *Handler) MachineMovements(w http.ResponseWriter, r *http.Request) {
	scope, ok := h.machine(w, r, ScopeGateRead)
	if !ok {
		return
	}
	since := h.now().Add(-24 * time.Hour)
	if raw := r.URL.Query().Get("since"); raw != "" {
		parsed, err := time.Parse(time.RFC3339, raw)
		if err != nil {
			httpx.Fail(r.Context(), w, r, errs.BadField("since", "must be an RFC 3339 instant"))
			return
		}
		if parsed.Before(h.now().AddDate(0, 0, -30)) {
			httpx.Fail(r.Context(), w, r, errs.BadField("since", "may not reach back more than 30 days"))
			return
		}
		since = parsed.UTC()
	}
	items, err := h.svc.MachineMovements(r.Context(), scope.TenantID, since, 200)
	if err != nil {
		httpx.Fail(r.Context(), w, r, err)
		return
	}
	httpx.OK(w, map[string]any{"items": items, "since": since})
}

// The reads live in Service so the handler has no query of its own.

func (s *Service) MachineVisitors(ctx context.Context, tenantID int64, limit int) ([]json.RawMessage, error) {
	enabled, err := s.enabled(ctx, tenantID)
	if err != nil {
		return nil, err
	}
	if !enabled {
		return nil, errs.ModuleDisabled(ModuleKey)
	}
	return s.repo.MachineVisitors(ctx, tenantID, limit)
}

