-- =============================================================================
-- 0022 module / reports & scheduled exports — on-demand analytics and digests
-- The definition catalogue is global; a tenant only gets rows for modules it has
-- enabled, which the report builder checks against tenant_modules at run time.
-- A schedule fires on the tenant's own day and time, renders pdf, xlsx or csv
-- and mails the admins. Output files carry an expiry so old exports are purged.
-- Re-runnable: CREATE TABLE IF NOT EXISTS only.
-- =============================================================================

CREATE TABLE IF NOT EXISTS report_definitions (
    id                      SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT,
    definition_key          VARCHAR(64)     NOT NULL,
    name                    VARCHAR(128)    NOT NULL,
    module_key              VARCHAR(64)     NOT NULL COMMENT 'a tenant without this module never sees the report',
    description             VARCHAR(512)    NULL,
    period_grain            VARCHAR(16)     NOT NULL DEFAULT 'day',
    allowed_groupings       JSON            NULL COMMENT 'gate, site, pass_type, host, department, guard',
    allowed_filters         JSON            NULL,
    default_columns         JSON            NULL,
    default_format          VARCHAR(8)      NOT NULL DEFAULT 'xlsx',
    is_default              TINYINT(1)      NOT NULL DEFAULT 0 COMMENT 'turned on for every new tenant',
    sort_order              SMALLINT        NOT NULL DEFAULT 100,
    status                  VARCHAR(16)     NOT NULL DEFAULT 'active',
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_report_definitions_key (definition_key),
    KEY idx_report_definitions_module (module_key, status, sort_order),
    CONSTRAINT fk_report_definitions_module FOREIGN KEY (module_key) REFERENCES modules (module_key) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_report_definitions_grain CHECK (period_grain IN ('hour', 'day', 'week', 'month', 'quarter', 'year', 'shift')),
    CONSTRAINT chk_report_definitions_format CHECK (default_format IN ('pdf', 'xlsx', 'csv')),
    CONSTRAINT chk_report_definitions_default CHECK (is_default IN (0, 1)),
    CONSTRAINT chk_report_definitions_status CHECK (status IN ('active', 'beta', 'retired'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS report_schedules (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    definition_key          VARCHAR(64)     NOT NULL,
    name                    VARCHAR(255)    NOT NULL,
    frequency               VARCHAR(12)     NOT NULL,
    day_of_week             TINYINT UNSIGNED NULL COMMENT 'ISO 1 Monday .. 7 Sunday, weekly only',
    day_of_month            TINYINT UNSIGNED NULL COMMENT '1 .. 28, monthly only, avoids month-end drift',
    hour_of_day             TINYINT UNSIGNED NOT NULL DEFAULT 7,
    minute_of_hour          TINYINT UNSIGNED NOT NULL DEFAULT 0,
    timezone                VARCHAR(64)     NOT NULL DEFAULT 'Africa/Nairobi' COMMENT 'tenant wall clock, not UTC',
    lookback_days           SMALLINT UNSIGNED NOT NULL DEFAULT 1,
    params                  JSON            NULL COMMENT 'groupings, filters and columns for this schedule',
    format                  VARCHAR(8)      NOT NULL DEFAULT 'pdf',
    recipients              JSON            NULL COMMENT 'array of email addresses',
    recipient_roles         JSON            NULL COMMENT 'array of role keys resolved at run time',
    send_to_tenant_admins   TINYINT(1)      NOT NULL DEFAULT 1,
    is_active               TINYINT(1)      NOT NULL DEFAULT 1,
    next_run_at             DATETIME(6)     NULL COMMENT 'stored in UTC, computed from the schedule timezone',
    last_run_at             DATETIME(6)     NULL,
    last_status             VARCHAR(16)     NULL,
    last_error              VARCHAR(512)    NULL,
    created_by              BIGINT UNSIGNED NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at              DATETIME(6)     NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_report_schedules_name (tenant_id, name),
    KEY idx_report_schedules_next (is_active, next_run_at),
    KEY idx_report_schedules_tenant (tenant_id, definition_key, is_active),
    CONSTRAINT fk_report_schedules_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_report_schedules_definition FOREIGN KEY (definition_key) REFERENCES report_definitions (definition_key) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_report_schedules_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_report_schedules_frequency CHECK (frequency IN ('hourly', 'daily', 'weekly', 'monthly')),
    CONSTRAINT chk_report_schedules_dow CHECK (day_of_week IS NULL OR day_of_week BETWEEN 1 AND 7),
    CONSTRAINT chk_report_schedules_dom CHECK (day_of_month IS NULL OR day_of_month BETWEEN 1 AND 28),
    CONSTRAINT chk_report_schedules_hour CHECK (hour_of_day BETWEEN 0 AND 23 AND minute_of_hour BETWEEN 0 AND 59),
    CONSTRAINT chk_report_schedules_format CHECK (format IN ('pdf', 'xlsx', 'csv')),
    CONSTRAINT chk_report_schedules_flags CHECK (is_active IN (0, 1) AND send_to_tenant_admins IN (0, 1)),
    CONSTRAINT chk_report_schedules_last_status CHECK (last_status IS NULL OR last_status IN ('succeeded', 'failed', 'skipped'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS report_runs (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    definition_key          VARCHAR(64)     NOT NULL,
    report_schedule_id      BIGINT UNSIGNED NULL,
    triggered_by            VARCHAR(16)     NOT NULL DEFAULT 'manual',
    period_from             DATETIME(6)     NULL,
    period_to               DATETIME(6)     NULL,
    params                  JSON            NULL,
    format                  VARCHAR(8)      NOT NULL DEFAULT 'xlsx',
    status                  VARCHAR(16)     NOT NULL DEFAULT 'queued',
    started_at              DATETIME(6)     NULL,
    finished_at             DATETIME(6)     NULL,
    duration_ms             INT UNSIGNED    NULL,
    row_count               INT UNSIGNED    NULL,
    file_path               VARCHAR(512)    NULL,
    file_name               VARCHAR(255)    NULL,
    file_size_bytes         BIGINT UNSIGNED NULL,
    checksum_sha256         CHAR(64)        NULL,
    error_code              VARCHAR(48)     NULL,
    error_message           VARCHAR(512)    NULL,
    delivered_at            DATETIME(6)     NULL COMMENT 'when the mail or webhook handoff succeeded',
    delivery_error          VARCHAR(512)    NULL,
    expires_at              DATETIME(6)     NULL COMMENT 'the generated file is purged on this date',
    purged_at               DATETIME(6)     NULL,
    requested_by_user_id    BIGINT UNSIGNED NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    KEY idx_report_runs_queue (status, created_at),
    KEY idx_report_runs_tenant (tenant_id, definition_key, created_at),
    KEY idx_report_runs_schedule (report_schedule_id, started_at),
    KEY idx_report_runs_purge (tenant_id, expires_at, purged_at),
    CONSTRAINT fk_report_runs_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_report_runs_definition FOREIGN KEY (definition_key) REFERENCES report_definitions (definition_key) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_report_runs_schedule FOREIGN KEY (report_schedule_id) REFERENCES report_schedules (id) ON DELETE SET NULL,
    CONSTRAINT fk_report_runs_requester FOREIGN KEY (requested_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_report_runs_triggered CHECK (triggered_by IN ('schedule', 'manual', 'api', 'backfill')),
    CONSTRAINT chk_report_runs_format CHECK (format IN ('pdf', 'xlsx', 'csv')),
    CONSTRAINT chk_report_runs_status CHECK (status IN ('queued', 'running', 'succeeded', 'failed', 'cancelled')),
    CONSTRAINT chk_report_runs_period CHECK (period_to IS NULL OR period_from IS NULL OR period_to >= period_from)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;
