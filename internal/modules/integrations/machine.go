// MachineVisitors returns the fields an integration needs and nothing that would make this a
// second copy of the visitor register.
func (r *Repository) MachineVisitors(ctx context.Context, tenantID int64,
	limit int) ([]json.RawMessage, error) {
	const query = `SELECT JSON_OBJECT(
			'id', v.id, 'first_name', v.first_name, 'last_name', v.last_name,
			'company_id', v.visitor_company_id, 'status', v.status,
			'visit_count', v.visit_count, 'last_visited_at', v.last_visited_at)
		FROM visitors v
		WHERE v.tenant_id = ? AND v.deleted_at IS NULL
		ORDER BY v.id DESC LIMIT ?`
	return r.rawRows(ctx, query, tenantID, limit)
}

func (r *Repository) MachinePass(ctx context.Context, tenantID int64,
	number string) (json.RawMessage, error) {
	const query = `SELECT JSON_OBJECT(
			'id', p.id, 'pass_no', p.pass_no, 'status', p.status,
			'category_key', p.category_key, 'source_module_key', p.source_module_key,
			'subject_name', p.subject_name, 'site_id', p.site_id,
			'valid_from', p.valid_from, 'valid_until', p.valid_until,
			'entry_count', p.entry_count, 'exit_count', p.exit_count)
		FROM passes p
		WHERE p.tenant_id = ? AND p.pass_no = ? AND p.deleted_at IS NULL LIMIT 1`
	var raw sql.NullString
	err := r.q.GetContext(ctx, &raw, query, tenantID, number)
	if errors.Is(err, sql.ErrNoRows) {
		return nil, errs.NotFound("pass")
	}
	if err != nil {
		return nil, err
	}
	if !raw.Valid {
		return nil, errs.NotFound("pass")
	}
	return json.RawMessage(raw.String), nil
}

func (r *Repository) MachineMovements(ctx context.Context, tenantID int64, since time.Time,
	limit int) ([]json.RawMessage, error) {
	const query = `SELECT JSON_OBJECT(
			'id', m.id, 'pass_id', m.pass_id, 'gate_id', m.gate_id,
			'direction', m.direction, 'result', m.result,
			'occurred_at', m.occurred_at, 'guard_user_id', m.guard_user_id)
		FROM gate_movements m
		WHERE m.tenant_id = ? AND m.occurred_at >= ?
		ORDER BY m.occurred_at DESC, m.id DESC LIMIT ?`
	return r.rawRows(ctx, query, tenantID, since, limit)
}

// rawRows selects database-built JSON objects. The shape is fixed by the query, so there is no
// struct to drift from the columns and no scan of a NULL into a string.
func (r *Repository) rawRows(ctx context.Context, query string, args ...any) ([]json.RawMessage, error) {
	var values []string
	if err := r.q.SelectContext(ctx, &values, query, args...); err != nil {
		return nil, err
	}
	out := make([]json.RawMessage, 0, len(values))
	for _, value := range values {
		out = append(out, json.RawMessage(value))
	}
	return out, nil
}
