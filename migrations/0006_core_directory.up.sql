CREATE TABLE IF NOT EXISTS departments (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    parent_id               BIGINT UNSIGNED NULL,
    code                    VARCHAR(32)     NOT NULL,
    name                    VARCHAR(255)    NOT NULL,
    cost_center             VARCHAR(64)     NULL,
    head_user_id            BIGINT UNSIGNED NULL,
    approval_threshold_value DECIMAL(14, 2) NULL COMMENT 'spending or value above which a higher approver is required',
    is_active               TINYINT(1)      NOT NULL DEFAULT 1,
    sort_order              SMALLINT        NOT NULL DEFAULT 100,
    external_ref            VARCHAR(128)    NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at              DATETIME(6)     NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_departments_code (tenant_id, code),
    UNIQUE KEY uk_departments_external_ref (tenant_id, external_ref),
    KEY idx_departments_parent (parent_id),
    KEY idx_departments_active (tenant_id, is_active),
    CONSTRAINT fk_departments_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_departments_parent FOREIGN KEY (parent_id) REFERENCES departments (id) ON DELETE RESTRICT,
    CONSTRAINT fk_departments_head FOREIGN KEY (head_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_departments_active CHECK (is_active IN (0, 1))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS staff (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    user_id                 BIGINT UNSIGNED NULL COMMENT 'NULL when the employee has no login',
    home_site_id            BIGINT UNSIGNED NULL,
    department_id           BIGINT UNSIGNED NULL,
    supervisor_id           BIGINT UNSIGNED NULL,
    employee_no             VARCHAR(64)     NOT NULL,
    first_name              VARCHAR(128)    NOT NULL,
    last_name               VARCHAR(128)    NOT NULL,
    job_title               VARCHAR(128)    NULL,
    employment_type         VARCHAR(24)     NOT NULL DEFAULT 'employee',
    phone                   VARCHAR(32)     NULL,
    email                   VARCHAR(255)    NULL,
    id_type                 VARCHAR(24)     NULL,
    id_number               VARCHAR(64)     NULL COMMENT 'auto-purged by the retention policy, see id_number_purged_at',
    id_number_purged_at     DATETIME(6)     NULL,
    photo_path              VARCHAR(512)    NULL COMMENT 'auto-purged with the visitor photo retention rule',
    photo_purged_at         DATETIME(6)     NULL,
    access_card_no          VARCHAR(64)     NULL,
    shift_pattern           VARCHAR(64)     NULL,
    status                  VARCHAR(16)     NOT NULL DEFAULT 'active',
    started_on              DATE            NULL,
    ended_on                DATE            NULL,
    external_ref            VARCHAR(128)    NULL,
    synced_at               DATETIME(6)     NULL,
    created_by              BIGINT UNSIGNED NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at              DATETIME(6)     NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_staff_employee_no (tenant_id, employee_no),
    UNIQUE KEY uk_staff_user (tenant_id, user_id),
    UNIQUE KEY uk_staff_external_ref (tenant_id, external_ref),
    UNIQUE KEY uk_staff_id_tenant (id, tenant_id),
    KEY idx_staff_name (tenant_id, last_name, first_name),
    KEY idx_staff_department (tenant_id, department_id, status),
    KEY idx_staff_phone (tenant_id, phone),
    KEY idx_staff_supervisor (supervisor_id),
    CONSTRAINT fk_staff_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_staff_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_staff_site FOREIGN KEY (home_site_id) REFERENCES sites (id) ON DELETE SET NULL,
    CONSTRAINT fk_staff_department FOREIGN KEY (department_id) REFERENCES departments (id) ON DELETE SET NULL,
    CONSTRAINT fk_staff_supervisor FOREIGN KEY (supervisor_id) REFERENCES staff (id) ON DELETE SET NULL,
    CONSTRAINT fk_staff_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_staff_employment CHECK (employment_type IN ('employee', 'contract_worker', 'casual', 'intern', 'outsourced')),
    CONSTRAINT chk_staff_status CHECK (status IN ('active', 'on_leave', 'suspended', 'exited', 'archived')),
    CONSTRAINT chk_staff_name_required CHECK (CHAR_LENGTH(TRIM(first_name)) > 0 AND CHAR_LENGTH(TRIM(last_name)) > 0)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;
