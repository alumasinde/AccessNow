-- =============================================================================
-- 0021 module / emergency roll-call — who was on site when the alarm went off
-- Opening an incident freezes the roster from the open movements across every
-- enabled module, so people marked accounted later still appear against the
-- snapshot. Guards scan or tap names at the muster point.
-- Re-runnable: CREATE TABLE IF NOT EXISTS only.
-- =============================================================================

CREATE TABLE IF NOT EXISTS evacuation_incidents (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    uuid                    CHAR(36)        NOT NULL,
    site_id                 BIGINT UNSIGNED NOT NULL,
    gate_id                 BIGINT UNSIGNED NULL COMMENT 'the gate that raised it, NULL = raised centrally',
    kind                    VARCHAR(24)     NOT NULL,
    status                  VARCHAR(16)     NOT NULL DEFAULT 'open',
    started_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    started_by_user_id      BIGINT UNSIGNED NULL,
    roster_frozen_at        DATETIME(6)     NULL,
    expected_person_count   INT UNSIGNED    NOT NULL DEFAULT 0,
    accounted_count         INT UNSIGNED    NOT NULL DEFAULT 0,
    muster_point            VARCHAR(255)    NULL,
    closed_at               DATETIME(6)     NULL,
    closed_by_user_id       BIGINT UNSIGNED NULL,
    summary                 TEXT            NULL,
    notes                   TEXT            NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_evacuation_incidents_uuid (uuid),
    UNIQUE KEY uk_evacuation_incidents_id_tenant (id, tenant_id),
    KEY idx_evacuation_incidents_open (tenant_id, status, started_at),
    KEY idx_evacuation_incidents_site (site_id, started_at),
    CONSTRAINT fk_evacuation_incidents_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_evacuation_incidents_site FOREIGN KEY (site_id, tenant_id) REFERENCES sites (id, tenant_id) ON DELETE RESTRICT,
    CONSTRAINT fk_evacuation_incidents_gate FOREIGN KEY (gate_id) REFERENCES gates (id) ON DELETE SET NULL,
    CONSTRAINT fk_evacuation_incidents_starter FOREIGN KEY (started_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_evacuation_incidents_closer FOREIGN KEY (closed_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_evacuation_incidents_kind CHECK (kind IN ('fire', 'medical', 'security', 'evacuation_drill', 'natural_hazard', 'chemical', 'other')),
    CONSTRAINT chk_evacuation_incidents_status CHECK (status IN ('open', 'in_progress', 'closed', 'cancelled')),
    CONSTRAINT chk_evacuation_incidents_window CHECK (closed_at IS NULL OR closed_at >= started_at)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS evacuation_roster (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    evacuation_incident_id  BIGINT UNSIGNED NOT NULL,
    person_key              VARCHAR(96)     NOT NULL COMMENT 'visitor:4412, staff:19, contractor:300, pass:881',
    person_type             VARCHAR(16)     NOT NULL,
    pass_id                 BIGINT UNSIGNED NULL,
    movement_id             BIGINT UNSIGNED NULL,
    gate_session_id         BIGINT UNSIGNED NULL,
    name_snapshot           VARCHAR(255)    NOT NULL,
    phone_snapshot          VARCHAR(32)     NULL,
    company_snapshot        VARCHAR(255)    NULL,
    plate_snapshot          VARCHAR(32)     NULL,
    last_seen_at            DATETIME(6)     NULL,
    last_seen_gate_id       BIGINT UNSIGNED NULL,
    department_id           BIGINT UNSIGNED NULL,
    status                  VARCHAR(24)     NOT NULL DEFAULT 'unaccounted',
    marked_by_user_id       BIGINT UNSIGNED NULL,
    marked_at               DATETIME(6)     NULL,
    marked_gate_id          BIGINT UNSIGNED NULL,
    muster_point            VARCHAR(255)    NULL,
    source                  VARCHAR(16)     NOT NULL DEFAULT 'scan',
    note                    VARCHAR(512)    NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_evacuation_roster_person (evacuation_incident_id, person_key),
    UNIQUE KEY uk_evacuation_roster_id_tenant (id, tenant_id),
    KEY idx_evacuation_roster_status (tenant_id, evacuation_incident_id, status),
    KEY idx_evacuation_roster_pass (pass_id),
    CONSTRAINT fk_evacuation_roster_incident FOREIGN KEY (evacuation_incident_id, tenant_id) REFERENCES evacuation_incidents (id, tenant_id) ON DELETE CASCADE,
    CONSTRAINT fk_evacuation_roster_pass FOREIGN KEY (pass_id) REFERENCES passes (id) ON DELETE SET NULL,
    CONSTRAINT fk_evacuation_roster_movement FOREIGN KEY (movement_id) REFERENCES gate_movements (id) ON DELETE SET NULL,
    CONSTRAINT fk_evacuation_roster_session FOREIGN KEY (gate_session_id) REFERENCES gate_sessions (id) ON DELETE SET NULL,
    CONSTRAINT fk_evacuation_roster_last_gate FOREIGN KEY (last_seen_gate_id) REFERENCES gates (id) ON DELETE SET NULL,
    CONSTRAINT fk_evacuation_roster_marked_gate FOREIGN KEY (marked_gate_id) REFERENCES gates (id) ON DELETE SET NULL,
    CONSTRAINT fk_evacuation_roster_department FOREIGN KEY (department_id) REFERENCES departments (id) ON DELETE SET NULL,
    CONSTRAINT fk_evacuation_roster_marker FOREIGN KEY (marked_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_evacuation_roster_type CHECK (person_type IN ('visitor', 'staff', 'contractor', 'driver', 'guard', 'other')),
    CONSTRAINT chk_evacuation_roster_status CHECK (status IN ('unaccounted', 'accounted', 'evacuated', 'injured', 'missing', 'not_on_site', 'deceased')),
    CONSTRAINT chk_evacuation_roster_source CHECK (source IN ('scan', 'manual', 'import', 'system'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS roll_call_marks (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    evacuation_incident_id  BIGINT UNSIGNED NOT NULL,
    evacuation_roster_id    BIGINT UNSIGNED NOT NULL,
    from_status             VARCHAR(24)     NULL,
    to_status               VARCHAR(24)     NOT NULL,
    marked_by_user_id       BIGINT UNSIGNED NULL,
    gate_id                 BIGINT UNSIGNED NULL,
    gate_session_id         BIGINT UNSIGNED NULL,
    muster_point            VARCHAR(255)    NULL,
    occurred_at             DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    note                    VARCHAR(512)    NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    KEY idx_roll_call_marks_roster (evacuation_roster_id, occurred_at),
    KEY idx_roll_call_marks_incident (evacuation_incident_id, occurred_at),
    CONSTRAINT fk_roll_call_marks_incident FOREIGN KEY (evacuation_incident_id, tenant_id) REFERENCES evacuation_incidents (id, tenant_id) ON DELETE CASCADE,
    CONSTRAINT fk_roll_call_marks_roster FOREIGN KEY (evacuation_roster_id, tenant_id) REFERENCES evacuation_roster (id, tenant_id) ON DELETE CASCADE,
    CONSTRAINT fk_roll_call_marks_marker FOREIGN KEY (marked_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_roll_call_marks_gate FOREIGN KEY (gate_id) REFERENCES gates (id) ON DELETE SET NULL,
    CONSTRAINT fk_roll_call_marks_session FOREIGN KEY (gate_session_id) REFERENCES gate_sessions (id) ON DELETE SET NULL,
    CONSTRAINT chk_roll_call_marks_status CHECK (to_status IN ('unaccounted', 'accounted', 'evacuated', 'injured', 'missing', 'not_on_site', 'deceased'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;
