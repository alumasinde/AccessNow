-- =============================================================================
-- 0010 module / visitor management — companies, people, visits, pre-registration
-- A visit is the module detail row of a passes header (pass_type visitor.*).
-- The flow lives on the pass: PENDING, APPROVED, ON_SITE, COMPLETED plus
-- REJECTED, EXPIRED, CANCELLED. Host approval itself is an approvals row (0017).
-- Re-runnable: CREATE TABLE IF NOT EXISTS only.
-- =============================================================================

CREATE TABLE IF NOT EXISTS visitor_companies (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    name                    VARCHAR(255)    NOT NULL,
    short_name              VARCHAR(64)     NULL,
    registration_no         VARCHAR(64)     NULL,
    tax_id                  VARCHAR(64)     NULL,
    industry                VARCHAR(128)    NULL,
    address                 VARCHAR(255)    NULL,
    city                    VARCHAR(128)    NULL,
    country                 CHAR(2)         NULL,
    contact_name            VARCHAR(128)    NULL,
    contact_email           VARCHAR(255)    NULL,
    contact_phone           VARCHAR(32)     NULL,
    status                  VARCHAR(16)     NOT NULL DEFAULT 'active',
    notes                   TEXT            NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at              DATETIME(6)     NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_visitor_companies_reg (tenant_id, registration_no),
    UNIQUE KEY uk_visitor_companies_id_tenant (id, tenant_id),
    KEY idx_visitor_companies_name (tenant_id, name, deleted_at),
    CONSTRAINT fk_visitor_companies_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT chk_visitor_companies_status CHECK (status IN ('active', 'prospect', 'inactive', 'archived'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS visitors (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    visitor_company_id      BIGINT UNSIGNED NULL,
    first_name              VARCHAR(128)    NOT NULL,
    last_name               VARCHAR(128)    NOT NULL,
    email                   VARCHAR(255)    NULL,
    phone                   VARCHAR(32)     NULL,
    nationality             CHAR(2)         NULL,
    date_of_birth           DATE            NULL,
    id_type                 VARCHAR(24)     NULL,
    id_number               VARCHAR(64)     NULL COMMENT 'purged by the compliance retention job',
    id_number_purged_at     DATETIME(6)     NULL,
    id_authority            VARCHAR(128)    NULL,
    photo_path              VARCHAR(512)    NULL COMMENT 'purged by the compliance retention job',
    photo_purged_at         DATETIME(6)     NULL,
    badge_no                VARCHAR(64)     NULL,
    preferred_host_user_id  BIGINT UNSIGNED NULL,
    is_vip                  TINYINT(1)      NOT NULL DEFAULT 0,
    visit_count             INT UNSIGNED    NOT NULL DEFAULT 0,
    last_visited_at         DATETIME(6)     NULL,
    status                  VARCHAR(16)     NOT NULL DEFAULT 'unverified',
    notes                   TEXT            NULL,
    external_ref            VARCHAR(128)    NULL,
    created_by              BIGINT UNSIGNED NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at              DATETIME(6)     NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_visitors_email (tenant_id, email),
    UNIQUE KEY uk_visitors_external_ref (tenant_id, external_ref),
    UNIQUE KEY uk_visitors_id_tenant (id, tenant_id),
    KEY idx_visitors_name (tenant_id, last_name, first_name, deleted_at),
    KEY idx_visitors_phone (tenant_id, phone),
    KEY idx_visitors_id_number (tenant_id, id_number),
    KEY idx_visitors_company (visitor_company_id),
    KEY idx_visitors_activity (tenant_id, last_visited_at),
    FULLTEXT KEY ft_visitors_name (first_name, last_name),
    CONSTRAINT fk_visitors_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_visitors_company FOREIGN KEY (visitor_company_id) REFERENCES visitor_companies (id) ON DELETE SET NULL,
    CONSTRAINT fk_visitors_host FOREIGN KEY (preferred_host_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_visitors_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_visitors_status CHECK (status IN ('unverified', 'verified', 'active', 'archived')),
    CONSTRAINT chk_visitors_id_type CHECK (id_type IS NULL OR id_type IN ('national_id', 'passport', 'drivers_licence', 'work_permit', 'refugee_id', 'other')),
    CONSTRAINT chk_visitors_name_required CHECK (CHAR_LENGTH(TRIM(first_name)) > 0 AND CHAR_LENGTH(TRIM(last_name)) > 0)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS visits (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    pass_id                 BIGINT UNSIGNED NOT NULL,
    visitor_id              BIGINT UNSIGNED NOT NULL,
    visitor_company_id      BIGINT UNSIGNED NULL,
    host_user_id            BIGINT UNSIGNED NULL,
    host_staff_id           BIGINT UNSIGNED NULL,
    host_name_snapshot      VARCHAR(255)    NULL,
    host_phone_snapshot     VARCHAR(32)     NULL,
    host_email_snapshot     VARCHAR(255)    NULL,
    department_id           BIGINT UNSIGNED NULL,
    pre_registration_id     BIGINT UNSIGNED NULL COMMENT 'visit_preauthorizations.id, indexed not enforced, the two tables reference each other',
    purpose                 VARCHAR(512)    NOT NULL,
    people_count            SMALLINT UNSIGNED NOT NULL DEFAULT 1,
    escort_required         TINYINT(1)      NOT NULL DEFAULT 0,
    escort_name             VARCHAR(128)    NULL,
    badge_no                VARCHAR(64)     NULL,
    is_walk_in              TINYINT(1)      NOT NULL DEFAULT 0,
    host_notified_at        DATETIME(6)     NULL,
    host_responded_at       DATETIME(6)     NULL,
    host_response           VARCHAR(16)     NULL,
    checked_in_at           DATETIME(6)     NULL,
    checked_in_gate_id      BIGINT UNSIGNED NULL,
    check_in_movement_id    BIGINT UNSIGNED NULL,
    checked_out_at          DATETIME(6)     NULL,
    checked_out_gate_id     BIGINT UNSIGNED NULL,
    check_out_movement_id   BIGINT UNSIGNED NULL,
    status                  VARCHAR(24)     NOT NULL DEFAULT 'pending',
    expected_from           DATETIME(6)     NULL,
    expected_until          DATETIME(6)     NULL,
    notes                   TEXT            NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_visits_pass (pass_id),
    KEY idx_visits_visitor (tenant_id, visitor_id, status),
    KEY idx_visits_host (tenant_id, host_user_id, status),
    KEY idx_visits_company (visitor_company_id),
    KEY idx_visits_on_site (tenant_id, status, checked_in_at),
    KEY idx_visits_preauth (pre_registration_id),
    CONSTRAINT fk_visits_pass FOREIGN KEY (pass_id, tenant_id) REFERENCES passes (id, tenant_id) ON DELETE CASCADE,
    CONSTRAINT fk_visits_visitor FOREIGN KEY (visitor_id, tenant_id) REFERENCES visitors (id, tenant_id) ON DELETE RESTRICT,
    CONSTRAINT fk_visits_company FOREIGN KEY (visitor_company_id) REFERENCES visitor_companies (id) ON DELETE SET NULL,
    CONSTRAINT fk_visits_host_user FOREIGN KEY (host_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_visits_host_staff FOREIGN KEY (host_staff_id) REFERENCES staff (id) ON DELETE SET NULL,
    CONSTRAINT fk_visits_department FOREIGN KEY (department_id) REFERENCES departments (id) ON DELETE SET NULL,
    CONSTRAINT fk_visits_check_in_gate FOREIGN KEY (checked_in_gate_id) REFERENCES gates (id) ON DELETE SET NULL,
    CONSTRAINT fk_visits_check_out_gate FOREIGN KEY (checked_out_gate_id) REFERENCES gates (id) ON DELETE SET NULL,
    CONSTRAINT fk_visits_check_in_movement FOREIGN KEY (check_in_movement_id) REFERENCES gate_movements (id) ON DELETE SET NULL,
    CONSTRAINT fk_visits_check_out_movement FOREIGN KEY (check_out_movement_id) REFERENCES gate_movements (id) ON DELETE SET NULL,
    CONSTRAINT chk_visits_status CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled', 'on_site', 'completed', 'expired', 'no_show')),
    CONSTRAINT chk_visits_host_response CHECK (host_response IS NULL OR host_response IN ('approved', 'rejected', 'delegated', 'expired')),
    CONSTRAINT chk_visits_flags CHECK (escort_required IN (0, 1) AND is_walk_in IN (0, 1))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS visit_preauthorizations (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    site_id                 BIGINT UNSIGNED NOT NULL,
    code                    VARCHAR(32)     NOT NULL COMMENT 'public link token the host emails to the visitor',
    visitor_id              BIGINT UNSIGNED NULL,
    visitor_company_id      BIGINT UNSIGNED NULL,
    visitor_name            VARCHAR(255)    NULL,
    visitor_email           VARCHAR(255)    NULL,
    visitor_phone           VARCHAR(32)     NULL,
    visitor_count           SMALLINT UNSIGNED NOT NULL DEFAULT 1,
    plate                   VARCHAR(32)     NULL,
    purpose                 VARCHAR(512)    NULL,
    host_user_id            BIGINT UNSIGNED NULL,
    host_email              VARCHAR(255)    NULL,
    created_by              BIGINT UNSIGNED NULL,
    status                  VARCHAR(16)     NOT NULL DEFAULT 'draft',
    sent_at                 DATETIME(6)     NULL,
    viewed_at               DATETIME(6)     NULL,
    accepted_at             DATETIME(6)     NULL,
    completed_at            DATETIME(6)     NULL,
    pass_id                 BIGINT UNSIGNED NULL COMMENT 'the pass created when the visitor completes the form',
    expires_at              DATETIME(6)     NOT NULL,
    details                 JSON            NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_visit_preauth_code (code),
    KEY idx_visit_preauth_tenant (tenant_id, status, expires_at),
    KEY idx_visit_preauth_host (host_user_id, status),
    CONSTRAINT fk_visit_preauth_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_visit_preauth_site FOREIGN KEY (site_id, tenant_id) REFERENCES sites (id, tenant_id) ON DELETE CASCADE,
    CONSTRAINT fk_visit_preauth_visitor FOREIGN KEY (visitor_id) REFERENCES visitors (id) ON DELETE SET NULL,
    CONSTRAINT fk_visit_preauth_company FOREIGN KEY (visitor_company_id) REFERENCES visitor_companies (id) ON DELETE SET NULL,
    CONSTRAINT fk_visit_preauth_host FOREIGN KEY (host_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_visit_preauth_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_visit_preauth_pass FOREIGN KEY (pass_id) REFERENCES passes (id) ON DELETE SET NULL,
    CONSTRAINT chk_visit_preauth_status CHECK (status IN ('draft', 'sent', 'viewed', 'accepted', 'completed', 'expired', 'cancelled'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;
