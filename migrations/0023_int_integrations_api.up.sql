-- =============================================================================
-- 0023 module / integrations & API — keys, webhooks, HR and ERP sync, actuators
-- No secret ever lands in this schema. api keys and provider credentials are
-- stored hashed or as a reference name into the vault or environment, and the
-- raw value is shown once at creation.
-- Re-runnable: CREATE TABLE IF NOT EXISTS only.
-- =============================================================================

CREATE TABLE IF NOT EXISTS api_keys (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    name                    VARCHAR(128)    NOT NULL,
    key_prefix              VARCHAR(16)     NOT NULL COMMENT 'first characters, shown in the UI so a key can be recognised',
    key_hash                CHAR(64)        NOT NULL COMMENT 'SHA-256 of the full secret',
    environment             VARCHAR(8)      NOT NULL DEFAULT 'live',
    scopes                  JSON            NULL COMMENT 'array of permission keys this key may use',
    rate_limit_per_minute   SMALLINT UNSIGNED NULL,
    allowed_origins         JSON            NULL,
    last_used_at            DATETIME(6)     NULL,
    usage_count             BIGINT UNSIGNED NOT NULL DEFAULT 0,
    expires_at              DATETIME(6)     NULL,
    revoked_at              DATETIME(6)     NULL,
    revoke_reason           VARCHAR(255)    NULL,
    status                  VARCHAR(16)     NOT NULL DEFAULT 'active',
    created_by              BIGINT UNSIGNED NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_api_keys_hash (key_hash),
    KEY idx_api_keys_tenant (tenant_id, status, last_used_at),
    CONSTRAINT fk_api_keys_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_api_keys_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_api_keys_environment CHECK (environment IN ('live', 'test')),
    CONSTRAINT chk_api_keys_status CHECK (status IN ('active', 'expired', 'revoked'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS webhook_endpoints (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    name                    VARCHAR(128)    NOT NULL,
    url                     VARCHAR(1024)   NOT NULL,
    secret_ref              VARCHAR(255)    NULL COMMENT 'vault or env name used to sign the payload, never the secret',
    events                  JSON            NULL COMMENT 'array of event keys, empty with subscribe_all = 0 means nothing',
    subscribe_all           TINYINT(1)      NOT NULL DEFAULT 0,
    timeout_ms              SMALLINT UNSIGNED NOT NULL DEFAULT 5000,
    max_retries             SMALLINT UNSIGNED NOT NULL DEFAULT 5,
    description             VARCHAR(512)    NULL,
    failure_count           INT UNSIGNED    NOT NULL DEFAULT 0,
    consecutive_failures    SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    last_success_at         DATETIME(6)     NULL,
    last_attempt_at         DATETIME(6)     NULL,
    disabled_reason         VARCHAR(255)    NULL,
    is_active               TINYINT(1)      NOT NULL DEFAULT 1,
    created_by              BIGINT UNSIGNED NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_webhook_endpoints_name (tenant_id, name),
    KEY idx_webhook_endpoints_active (tenant_id, is_active),
    CONSTRAINT fk_webhook_endpoints_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_webhook_endpoints_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_webhook_endpoints_url CHECK (url LIKE 'https://%'),
    CONSTRAINT chk_webhook_endpoints_flags CHECK (subscribe_all IN (0, 1) AND is_active IN (0, 1))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS webhook_deliveries (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    webhook_endpoint_id     BIGINT UNSIGNED NOT NULL,
    domain_event_id         BIGINT UNSIGNED NULL,
    event_key               VARCHAR(64)     NOT NULL,
    attempt                 SMALLINT UNSIGNED NOT NULL DEFAULT 1,
    payload_sha256          CHAR(64)        NULL,
    request_body            JSON            NULL COMMENT 'kept until the payload retention window, then nulled',
    request_body_purged_at  DATETIME(6)     NULL,
    response_status         SMALLINT UNSIGNED NULL,
    response_snippet        VARCHAR(1024)   NULL,
    error_message           VARCHAR(512)    NULL,
    status                  VARCHAR(16)     NOT NULL DEFAULT 'queued',
    queued_at               DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    available_at            DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    sent_at                 DATETIME(6)     NULL,
    duration_ms             INT UNSIGNED    NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_webhook_deliveries_attempt (domain_event_id, webhook_endpoint_id, attempt),
    KEY idx_webhook_deliveries_queue (status, available_at),
    KEY idx_webhook_deliveries_endpoint (webhook_endpoint_id, status, queued_at),
    KEY idx_webhook_deliveries_event (domain_event_id),
    CONSTRAINT fk_webhook_deliveries_endpoint FOREIGN KEY (webhook_endpoint_id) REFERENCES webhook_endpoints (id) ON DELETE CASCADE,
    CONSTRAINT fk_webhook_deliveries_event FOREIGN KEY (domain_event_id) REFERENCES domain_events (id) ON DELETE SET NULL,
    CONSTRAINT chk_webhook_deliveries_status CHECK (status IN ('queued', 'sending', 'succeeded', 'failed', 'dead', 'cancelled')),
    CONSTRAINT chk_webhook_deliveries_attempt CHECK (attempt >= 1)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS external_systems (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    kind                    VARCHAR(24)     NOT NULL,
    name                    VARCHAR(128)    NOT NULL,
    base_url                VARCHAR(1024)   NULL,
    auth_type               VARCHAR(16)     NOT NULL DEFAULT 'none',
    credentials_ref         VARCHAR(255)    NULL COMMENT 'vault or env name, never the secret',
    username                VARCHAR(128)    NULL,
    api_version             VARCHAR(32)     NULL,
    sync_direction          VARCHAR(8)      NOT NULL DEFAULT 'in',
    sync_frequency_minutes  SMALLINT UNSIGNED NULL,
    field_map               JSON            NULL COMMENT 'remote column to local column',
    options                 JSON            NULL,
    health_status           VARCHAR(16)     NOT NULL DEFAULT 'unknown',
    last_sync_at            DATETIME(6)     NULL,
    last_error              VARCHAR(512)    NULL,
    is_active               TINYINT(1)      NOT NULL DEFAULT 1,
    created_by              BIGINT UNSIGNED NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_external_systems_name (tenant_id, kind, name),
    UNIQUE KEY uk_external_systems_id_tenant (id, tenant_id),
    KEY idx_external_systems_schedule (is_active, sync_frequency_minutes, last_sync_at),
    CONSTRAINT fk_external_systems_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_external_systems_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_external_systems_kind CHECK (kind IN ('hr', 'erp', 'accounting', 'access_control', 'video', 'visitor_pre_registration', 'payment', 'other')),
    CONSTRAINT chk_external_systems_auth CHECK (auth_type IN ('none', 'basic', 'bearer', 'api_key', 'client_credentials', 'oauth2')),
    CONSTRAINT chk_external_systems_direction CHECK (sync_direction IN ('in', 'out', 'both')),
    CONSTRAINT chk_external_systems_health CHECK (health_status IN ('unknown', 'healthy', 'degraded', 'failing')),
    CONSTRAINT chk_external_systems_active CHECK (is_active IN (0, 1))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS external_entity_links (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    external_system_id      BIGINT UNSIGNED NOT NULL,
    entity_type             VARCHAR(32)     NOT NULL COMMENT 'staff, department, visitor_company, vehicle, cost_center',
    external_id             VARCHAR(128)    NOT NULL,
    internal_id             BIGINT UNSIGNED NULL,
    content_hash            CHAR(64)        NULL COMMENT 'hash of the last synced remote record, skips no-op writes',
    last_synced_at          DATETIME(6)     NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_external_entity_links (external_system_id, entity_type, external_id),
    KEY idx_external_entity_links_internal (tenant_id, entity_type, internal_id),
    CONSTRAINT fk_external_entity_links_system FOREIGN KEY (external_system_id, tenant_id) REFERENCES external_systems (id, tenant_id) ON DELETE CASCADE,
    CONSTRAINT chk_external_entity_links_type CHECK (entity_type IN ('staff', 'department', 'company', 'visitor_company', 'vehicle', 'cost_center', 'user', 'site'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS sync_jobs (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    external_system_id      BIGINT UNSIGNED NOT NULL,
    entity_type             VARCHAR(32)     NOT NULL,
    direction               VARCHAR(8)      NOT NULL DEFAULT 'in',
    trigger_source          VARCHAR(16)     NOT NULL DEFAULT 'schedule',
    status                  VARCHAR(16)     NOT NULL DEFAULT 'queued',
    records_seen            INT UNSIGNED    NOT NULL DEFAULT 0,
    records_created         INT UNSIGNED    NOT NULL DEFAULT 0,
    records_updated         INT UNSIGNED    NOT NULL DEFAULT 0,
    records_failed          INT UNSIGNED    NOT NULL DEFAULT 0,
    cursor_value            VARCHAR(255)    NULL COMMENT 'watermark for the next incremental run',
    error_summary           VARCHAR(1024)   NULL,
    started_at              DATETIME(6)     NULL,
    finished_at             DATETIME(6)     NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    KEY idx_sync_jobs_queue (status, created_at),
    KEY idx_sync_jobs_system (external_system_id, entity_type, finished_at),
    CONSTRAINT fk_sync_jobs_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_sync_jobs_system FOREIGN KEY (external_system_id) REFERENCES external_systems (id) ON DELETE CASCADE,
    CONSTRAINT chk_sync_jobs_direction CHECK (direction IN ('in', 'out')),
    CONSTRAINT chk_sync_jobs_trigger CHECK (trigger_source IN ('schedule', 'manual', 'api', 'webhook')),
    CONSTRAINT chk_sync_jobs_status CHECK (status IN ('queued', 'running', 'succeeded', 'partial', 'failed', 'cancelled'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS actuator_commands (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    gate_device_id          BIGINT UNSIGNED NULL,
    gate_id                 BIGINT UNSIGNED NOT NULL,
    pass_id                 BIGINT UNSIGNED NULL,
    movement_id             BIGINT UNSIGNED NULL,
    command                 VARCHAR(24)     NOT NULL,
    source                  VARCHAR(16)     NOT NULL DEFAULT 'approved_scan',
    status                  VARCHAR(16)     NOT NULL DEFAULT 'queued',
    attempts                SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    idempotency_key         CHAR(64)        NULL COMMENT 'one open per approved scan, no double gate lift',
    available_at            DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    queued_at               DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    sent_at                 DATETIME(6)     NULL,
    acked_at                DATETIME(6)     NULL,
    error_message           VARCHAR(512)    NULL,
    issued_by_user_id       BIGINT UNSIGNED NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_actuator_commands_idempotency (tenant_id, idempotency_key),
    KEY idx_actuator_commands_queue (status, available_at),
    KEY idx_actuator_commands_gate (gate_id, queued_at),
    KEY idx_actuator_commands_pass (pass_id),
    CONSTRAINT fk_actuator_commands_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_actuator_commands_device FOREIGN KEY (gate_device_id) REFERENCES gate_devices (id) ON DELETE SET NULL,
    CONSTRAINT fk_actuator_commands_gate FOREIGN KEY (gate_id) REFERENCES gates (id) ON DELETE CASCADE,
    CONSTRAINT fk_actuator_commands_pass FOREIGN KEY (pass_id) REFERENCES passes (id) ON DELETE SET NULL,
    CONSTRAINT fk_actuator_commands_movement FOREIGN KEY (movement_id) REFERENCES gate_movements (id) ON DELETE SET NULL,
    CONSTRAINT fk_actuator_commands_issuer FOREIGN KEY (issued_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_actuator_commands_command CHECK (command IN ('open_boom_gate', 'close_boom_gate', 'release_turnstile', 'barrier_up', 'door_unlock', 'light_on', 'siren', 'log_only')),
    CONSTRAINT chk_actuator_commands_source CHECK (source IN ('approved_scan', 'manual', 'api', 'emergency', 'rule')),
    CONSTRAINT chk_actuator_commands_status CHECK (status IN ('queued', 'sending', 'sent', 'confirmed', 'failed', 'timeout', 'cancelled'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;
