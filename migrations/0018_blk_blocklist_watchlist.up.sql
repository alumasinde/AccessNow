-- =============================================================================
-- 0018 module / blacklist & watchlist — screening on every check-in
-- Entries match on a normalised identifier stored as SHA-256, so a banned phone
-- or plate is searchable without a range index on the raw value.
-- A blacklist hit denies entry, a watchlist hit allows it and alerts the
-- supervisor quietly. Module off: no screening, check-in still works.
-- Re-runnable: CREATE TABLE IF NOT EXISTS only.
-- =============================================================================

CREATE TABLE IF NOT EXISTS blocklist_entries (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    list_type               VARCHAR(16)     NOT NULL DEFAULT 'blocklist',
    entity_type             VARCHAR(16)     NOT NULL,
    match_type              VARCHAR(24)     NOT NULL,
    match_value             VARCHAR(255)    NOT NULL COMMENT 'normalised value, uppercase and stripped of separators',
    match_hash              CHAR(64)        NOT NULL COMMENT 'SHA-256 of match_value, the comparison key',
    display_name            VARCHAR(255)    NULL,
    organisation            VARCHAR(255)    NULL,
    photo_path              VARCHAR(512)    NULL,
    reason                  VARCHAR(512)    NOT NULL,
    severity                VARCHAR(16)     NOT NULL DEFAULT 'high',
    source                  VARCHAR(64)     NULL COMMENT 'police, internal, tenant, incident, import',
    evidence_ref            VARCHAR(255)    NULL,
    incident_pass_id        BIGINT UNSIGNED NULL COMMENT 'the pass that triggered the listing',
    alert_supervisor_role_key VARCHAR(64)   NULL COMMENT 'who hears about a watchlist hit',
    hit_count               INT UNSIGNED    NOT NULL DEFAULT 0,
    last_hit_at             DATETIME(6)     NULL,
    status                  VARCHAR(16)     NOT NULL DEFAULT 'active',
    added_by_user_id        BIGINT UNSIGNED NULL,
    added_at                DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    expires_at              DATETIME(6)     NULL,
    revoked_at              DATETIME(6)     NULL,
    revoke_reason           VARCHAR(512)    NULL,
    notes                   TEXT            NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_blocklist_match (tenant_id, list_type, match_type, match_hash),
    UNIQUE KEY uk_blocklist_id_tenant (id, tenant_id),
    KEY idx_blocklist_active (tenant_id, status, list_type, expires_at),
    KEY idx_blocklist_display (tenant_id, display_name),
    KEY idx_blocklist_value (tenant_id, match_value),
    CONSTRAINT fk_blocklist_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_blocklist_incident FOREIGN KEY (incident_pass_id) REFERENCES passes (id) ON DELETE SET NULL,
    CONSTRAINT fk_blocklist_adder FOREIGN KEY (added_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_blocklist_list_type CHECK (list_type IN ('blocklist', 'watchlist')),
    CONSTRAINT chk_blocklist_entity CHECK (entity_type IN ('person', 'vehicle', 'company', 'device')),
    CONSTRAINT chk_blocklist_match CHECK (match_type IN ('id_number', 'phone', 'plate', 'email', 'name_hash', 'badge_no', 'card_no', 'photo_hash')),
    CONSTRAINT chk_blocklist_severity CHECK (severity IN ('low', 'medium', 'high')),
    CONSTRAINT chk_blocklist_status CHECK (status IN ('active', 'expired', 'revoked', 'under_review')),
    CONSTRAINT chk_blocklist_expiry CHECK (expires_at IS NULL OR expires_at > added_at)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;

CREATE TABLE IF NOT EXISTS blocklist_hits (
    id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id               BIGINT UNSIGNED NOT NULL,
    entry_id                BIGINT UNSIGNED NOT NULL,
    matched_on              VARCHAR(24)     NOT NULL,
    matched_value           VARCHAR(255)    NULL COMMENT 'the value that hit, purged by the retention policy',
    matched_value_purged_at DATETIME(6)     NULL,
    pass_id                 BIGINT UNSIGNED NULL,
    movement_id             BIGINT UNSIGNED NULL,
    scan_id                 BIGINT UNSIGNED NULL,
    gate_id                 BIGINT UNSIGNED NULL,
    gate_session_id         BIGINT UNSIGNED NULL,
    action_taken            VARCHAR(24)     NOT NULL,
    override_by_user_id     BIGINT UNSIGNED NULL,
    override_reason         VARCHAR(512)    NULL,
    alerted_user_ids        JSON            NULL,
    alert_sent_at           DATETIME(6)     NULL,
    occurred_at             DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    resolved_by_user_id     BIGINT UNSIGNED NULL,
    resolved_at             DATETIME(6)     NULL,
    resolution              VARCHAR(1024)   NULL,
    created_at              DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    KEY idx_blocklist_hits_entry (entry_id, occurred_at),
    KEY idx_blocklist_hits_tenant (tenant_id, action_taken, occurred_at),
    KEY idx_blocklist_hits_pass (pass_id),
    KEY idx_blocklist_hits_unresolved (tenant_id, resolved_at, occurred_at),
    CONSTRAINT fk_blocklist_hits_entry FOREIGN KEY (entry_id, tenant_id) REFERENCES blocklist_entries (id, tenant_id) ON DELETE CASCADE,
    CONSTRAINT fk_blocklist_hits_pass FOREIGN KEY (pass_id) REFERENCES passes (id) ON DELETE SET NULL,
    CONSTRAINT fk_blocklist_hits_movement FOREIGN KEY (movement_id) REFERENCES gate_movements (id) ON DELETE SET NULL,
    CONSTRAINT fk_blocklist_hits_scan FOREIGN KEY (scan_id) REFERENCES scan_attempts (id) ON DELETE SET NULL,
    CONSTRAINT fk_blocklist_hits_gate FOREIGN KEY (gate_id) REFERENCES gates (id) ON DELETE SET NULL,
    CONSTRAINT fk_blocklist_hits_session FOREIGN KEY (gate_session_id) REFERENCES gate_sessions (id) ON DELETE SET NULL,
    CONSTRAINT fk_blocklist_hits_override FOREIGN KEY (override_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_blocklist_hits_resolver FOREIGN KEY (resolved_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_blocklist_hits_matched CHECK (matched_on IN ('id_number', 'phone', 'plate', 'email', 'name_hash', 'badge_no', 'card_no', 'photo_hash')),
    CONSTRAINT chk_blocklist_hits_action CHECK (action_taken IN ('denied', 'allowed_with_alert', 'warned', 'override_granted'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC;
